def builtin_feature_uuid(feature_key: str) -> UUID:
	"""Deterministic UUIDv5 for built-in feature seeding & cross-environment parity."""
	return uuid5(NAMESPACE_DNS, f"usfds.builtin.feature.{feature_key}")


def builtin_feature_set_uuid(set_key: str) -> UUID:
	"""Deterministic UUIDv5 for built-in feature set seeding."""
	return uuid5(NAMESPACE_DNS, f"usfds.builtin.feature_set.{set_key}")


